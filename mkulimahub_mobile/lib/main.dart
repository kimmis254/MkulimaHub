import 'package:flutter/material.dart';
import 'package:flutter_dotenv/flutter_dotenv.dart'; // 🔥 Import dotenv
import 'package:firebase_core/firebase_core.dart'; // 🔥 Add Firebase Core
import 'firebase_options.dart'; // 🔥 Add Firebase Options (Generated by flutterfire)

import 'package:mkulimahub_mobile/core/api_client.dart';
import 'package:mkulimahub_mobile/features/auth/login_screen.dart';
import 'package:mkulimahub_mobile/features/home/home_screen.dart';
import 'package:mkulimahub_mobile/features/auth/welcome_screen.dart';
import 'package:mkulimahub_mobile/features/buyer/buyer_dashboard.dart';



Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized(); // Required for async main
  
  await dotenv.load(fileName: ".env"); // Load the variables
  
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  runApp(const MkulimaHubApp());
}

Future<Widget> _getInitialScreen(ApiClient apiClient) async {
  final token = await apiClient.getToken();

  // 1. If there is no token, they are fully logged out. Send to Front Door.
  if (token == null || token.isEmpty) {
    return const WelcomeScreen(); 
  }

  // 2. Instantly read the cached role from the phone (No internet required!)
  final role = await apiClient.getUserRole();
  
  if (role == 'buyer') {
    return const BuyerDashboard(); // 🏢 Route to Customer
  } 
  
  // 3. Default to Farmer Dashboard
  return const HomeScreen(); // 🚜 Route to Farmer
}

class MkulimaHubApp extends StatelessWidget {
  const MkulimaHubApp({super.key});

  @override
  Widget build(BuildContext context) {
    final ApiClient apiClient = ApiClient();

    return MaterialApp(
      title: 'MkulimaHub',
      debugShowCheckedModeBanner: false, // Cleaner production look
      theme: ThemeData(
        colorScheme: ColorScheme.fromSeed(seedColor: Colors.green),
        useMaterial3: true,
        inputDecorationTheme: InputDecorationTheme(
          border: OutlineInputBorder(borderRadius: BorderRadius.circular(12)),
          filled: true,
          fillColor: Colors.grey[100],
        ),
      ),
      home: FutureBuilder<Widget>(
  future: _getInitialScreen(apiClient), // Call our new helper method
  builder: (context, snapshot) {
    // While deciding where to send them, show a loading spinner
    if (snapshot.connectionState == ConnectionState.waiting) {
      return const Scaffold(
        backgroundColor: Colors.white,
        body: Center(
          child: CircularProgressIndicator(color: Colors.green)
        )
      );
    }
    
    // Once the decision is made, snap to that screen!
    return snapshot.data ?? const WelcomeScreen(); 
  },
),
    );
  }
}